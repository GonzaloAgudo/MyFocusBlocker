@Composable
fun ProtectionScreen(root: Root, onBack: () -> Unit) {
    val context = LocalContext.current
    val p = root.live.protection

    // Código recién generado: se muestra UNA vez y no se vuelve a poder consultar.
    var generated by remember { mutableStateOf<String?>(null) }
    var showRedeem by remember { mutableStateOf(false) }

    ScreenScaffold(title = "Protección", onBack = onBack) { padding ->
        ColumnScroll(padding) {
            Text(
                "Estas opciones evitan que te saltes tus propios bloqueos en un momento de debilidad.",
                style = MaterialTheme.typography.bodyMedium,
                color = MaterialTheme.colorScheme.onSurface.copy(alpha = 0.75f),
            )

            ToggleCard(
                title = "Modo estricto",
                desc = "Mientras haya un bloqueo activo no podrás editar ni desactivar reglas.",
                checked = p.strictMode,
            ) { context.toastFor(AppRepository.updateProtection(p.copy(strictMode = it))) }

            ToggleCard(
                title = "Retardo de cambios",
                desc = "Cualquier cambio que reduzca un bloqueo tardará un tiempo en aplicarse.",
                checked = p.delayEnabled,
            ) { context.toastFor(AppRepository.updateProtection(p.copy(delayEnabled = it))) }

            if (p.delayEnabled) {
                SectionCard {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Column(Modifier.weight(1f)) {
                            Text("Tiempo de retardo", fontWeight = FontWeight.SemiBold)
                            Text(
                                minutesToDuration(p.delayMinutes),
                                style = MaterialTheme.typography.bodySmall,
                                color = MaterialTheme.colorScheme.onSurface.copy(alpha = 0.7f),
                            )
                        }
                        IconButton(onClick = {
                            val v = (p.delayMinutes - 30).coerceAtLeast(30)
                            context.toastFor(AppRepository.updateProtection(p.copy(delayMinutes = v)))
                        }) { Icon(Icons.Default.Remove, "Menos") }
                        Text("${p.delayMinutes}m", fontWeight = FontWeight.Bold)
                        IconButton(onClick = {
                            val v = (p.delayMinutes + 30).coerceAtMost(1440)
                            context.toastFor(AppRepository.updateProtection(p.copy(delayMinutes = v)))
                        }) { Icon(Icons.Default.Add, "Más") }
                    }
                }
            }

            // --- Código de emergencia ---
            SectionCard("Código de emergencia") {
                Text(
                    if (p.guardianCodeHash != null)
                        "Configurado. Quien tenga el código puede desactivar el modo estricto y el retardo."
                    else
                        "Sin configurar. Genera uno y dáselo a alguien de confianza: será tu vía de " +
                            "escape si te quedas atrapado.",
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurface.copy(alpha = 0.7f),
                )
                Spacer(Modifier.size(12.dp))
                Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    OutlinedButton(
                        onClick = {
                            val code = GuardianCode.generate()
                            if (AppRepository.setGuardianCode(GuardianCode.hash(code))) {
                                generated = code
                            } else {
                                Toast.makeText(
                                    context,
                                    "Apaga el modo estricto para generar un código nuevo.",
                                    Toast.LENGTH_LONG,
                                ).show()
                            }
                        },
                        enabled = !p.strictMode,
                    ) { Text(if (p.guardianCodeHash != null) "Generar otro" else "Generar código") }

                    if (p.guardianCodeHash != null) {
                        Button(onClick = { showRedeem = true }) { Text("Usar código") }
                    }
                }
                if (p.strictMode) {
                    Spacer(Modifier.size(8.dp))
                    Text(
                        "No puedes generar un código nuevo con el modo estricto activo: si pudieras, " +
                            "bastaría con crearlo y leerlo para saltarte la protección.",
                        style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.onSurface.copy(alpha = 0.6f),
                    )
                }
                if (p.strictMode && p.guardianCodeHash == null) {
                    Spacer(Modifier.size(8.dp))
                    Text(
                        "Aviso: tienes el modo estricto sin código de emergencia. Para editar tendrás " +
                            "que esperar a que no haya ningún bloqueo activo.",
                        style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.error,
                    )
                }
            }

            ToggleCard(
                title = "Bloquear desinstalación",
                desc = "Activa el administrador de dispositivos: Android se niega a desinstalar la " +
                    "app. No interfiere con Ajustes.",
                checked = p.blockUninstall,
            ) { on ->
                val result = AppRepository.updateProtection(p.copy(blockUninstall = on))
                context.toastFor(result)
                if (on) {
                    if (!Permissions.deviceAdminActive(context)) {
                        runCatching { context.startActivity(Permissions.deviceAdminIntent(context)) }
                    }
                } else if (result is ChangeResult.Applied) {
                    // Solo al aplicarse de verdad: si no, seguiría sin poder desinstalarse.
                    Permissions.removeDeviceAdmin(context)
                }
            }

            ToggleCard(
                title = "Vigilar Ajustes (agresivo)",
                desc = "Además, te expulsa de la ficha de la app, de Accesibilidad y del " +
                    "administrador, para que tampoco puedas desactivarla. Desactivado por defecto: " +
                    "no hace falta para impedir la desinstalación.",
                checked = p.guardSettings,
            ) { context.toastFor(AppRepository.updateProtection(p.copy(guardSettings = it))) }

            if (p.blockUninstall && !Permissions.deviceAdminActive(context)) {
                SectionCard {
                    Text(
                        "Falta activar el Administrador de dispositivos para bloquear la desinstalación.",
                        style = MaterialTheme.typography.bodyMedium,
                        color = MaterialTheme.colorScheme.error,
                    )
                    Spacer(Modifier.size(8.dp))
                    OutlinedButton(onClick = {
                        runCatching { context.startActivity(Permissions.deviceAdminIntent(context)) }
                    }) { Text("Activar administrador") }
                }
            }
        }
    }

    generated?.let { code -> GeneratedCodeDialog(code) { generated = null } }
    if (showRedeem) RedeemCodeDialog { showRedeem = false }
}

/** Muestra el código recién generado. Es la única vez que se puede leer. */
@Composable
private fun GeneratedCodeDialog(code: String, onDismiss: () -> Unit) {
    val context = LocalContext.current
    AlertDialog(
        onDismissRequest = {},
        title = { Text("Tu código de emergencia") },
        text = {
            Column {
                Text(
                    code,
                    style = MaterialTheme.typography.headlineMedium,
                    fontWeight = FontWeight.Bold,
                )
                Spacer(Modifier.size(12.dp))
                Text(
                    "Dáselo a alguien de confianza AHORA. No se guarda en el teléfono (solo su " +
                        "huella), así que no podrás volver a verlo.",
                    style = MaterialTheme.typography.bodyMedium,
                )
            }
        },
        confirmButton = {
            TextButton(onClick = onDismiss) { Text("Ya lo he compartido") }
        },
        dismissButton = {
            TextButton(onClick = {
                val cb = context.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
                cb.setPrimaryClip(ClipData.newPlainText("Código de emergencia", code))
                Toast.makeText(context, "Copiado al portapapeles", Toast.LENGTH_SHORT).show()
            }) { Text("Copiar") }
        },
    )
}

/** Pide el código para desactivar las protecciones. */
@Composable
private fun RedeemCodeDialog(onDismiss: () -> Unit) {
    val context = LocalContext.current
    var input by remember { mutableStateOf("") }
    var error by remember { mutableStateOf(false) }

    AlertDialog(
        onDismissRequest = onDismiss,
        title = { Text("Usar código de emergencia") },
        text = {
            Column {
                Text("Desactivará el modo estricto y el retardo de cambios, y consumirá el código.")
                Spacer(Modifier.size(12.dp))
                OutlinedTextField(
                    value = input,
                    onValueChange = { input = it; error = false },
                    label = { Text("Código") },
                    singleLine = true,
                    isError = error,
                )
                if (error) {
                    Text(
                        "Código incorrecto.",
                        style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.error,
                    )
                }
            }
        },
        confirmButton = {
            TextButton(onClick = {
                if (AppRepository.redeemGuardianCode(input)) {
                    Toast.makeText(context, "Protecciones desactivadas", Toast.LENGTH_LONG).show()
                    onDismiss()
                } else {
                    error = true
                }
            }) { Text("Desactivar") }
        },
        dismissButton = { TextButton(onClick = onDismiss) { Text("Cancelar") } },
    )
}

@Composable
private fun ToggleCard(title: String, desc: String, checked: Boolean, onChange: (Boolean) -> Unit) {
    SectionCard {
        Row(verticalAlignment = Alignment.CenterVertically) {
            Column(Modifier.weight(1f)) {
                Text(title, fontWeight = FontWeight.SemiBold)
                Text(
                    desc,
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurface.copy(alpha = 0.7f),
                )
            }
            Spacer(Modifier.width(12.dp))
            Switch(checked = checked, onCheckedChange = onChange)
        }
    }
}
